// public/paste.js（貼り付けたカレンダーの読み取り）を確かめる。npm test で流す
import test from 'node:test';
import assert from 'node:assert/strict';
import '../public/paste.js';

const parse = (t, today = '2026-10-15') => globalThis.parsePaste(t, { today });
const brief = (items) => items.map((i) => [i.date, i.kind, i.st, i.en, i.practice].join(' '));

// 配っている 2026年10月 のカレンダーを、表計算ソフトから写したときの形（1週を日付の行と中身の行に分けたもの）
const T = '\t';
const GRID = [
  '2026年10月',
  ['日', '月', '火', '水', '木', '金', '土'].join(T),
  ['9月27日', '28日', '29日', '30日', '10月1日', '2日', '3日'].join(T),
  ['', '大崎市訪問演奏', '', '', '', '個人／パート', ''].join(T),
  ['', '', '', '', '', '18:00〜21:00', ''].join(T),
  ['4日', '5日', '6日', '7日', '8日', '9日', '10日'].join(T),
  ['個人／パート', '', '合奏', '', '月曜授業', '合奏', ''].join(T),
  ['13:00〜17:00', '', '18:30〜20:00', '', '', '18:30〜20:00', ''].join(T),
  ['', '', '個人／パート', '', '', '個人／パート', ''].join(T),
  ['', '', '20:00〜21:00', '', '', '20:00〜21:00', ''].join(T),
  ['11日', '12日', '13日', '14日', '15日', '16日', '17日'].join(T),
  ['個人／パート', 'スポーツの日', '合奏', '', '', '"仙フィル394th\n午後休講"', '大学祭演奏'].join(T),
  ['13:00〜17:00', '', '18:30〜20:00', '', '', '大学祭リハーサル', ''].join(T),
  ['', '', '個人／パート', '', '', '17:00〜19:30', ''].join(T),
  ['', '', '20:00〜21:00', '', '', '', ''].join(T),
  ['18日', '19日', '20日', '21日', '22日', '23日', '24日'].join(T),
  ['大学祭', '', '個人／パート', '', '', '', '総合型選抜'].join(T),
  ['', '', '18:00〜21:00', '', '', '', ''].join(T),
  ['25日', '26日', '27日', '28日', '29日', '30日', '31日'].join(T),
  ['総合型選抜', '', '個人／パート', '', '', '個人／パート', ''].join(T),
  ['', '', '18:00〜21:00', '', '', '18:00〜21:00', ''].join(T),
].join('\n');

test('表計算ソフトから写したカレンダーを読む', () => {
  const items = parse(GRID);
  assert.deepEqual(brief(items), [
    '2026-09-28 大崎市訪問演奏   true',
    '2026-10-02 個人／パート 18:00 21:00 true',
    '2026-10-04 個人／パート 13:00 17:00 true',
    '2026-10-06 合奏 18:30 20:00 true',
    '2026-10-06 個人／パート 20:00 21:00 true',
    '2026-10-08 月曜授業   false',
    '2026-10-09 合奏 18:30 20:00 true',
    '2026-10-09 個人／パート 20:00 21:00 true',
    '2026-10-11 個人／パート 13:00 17:00 true',
    '2026-10-12 スポーツの日   false',
    '2026-10-13 合奏 18:30 20:00 true',
    '2026-10-13 個人／パート 20:00 21:00 true',
    '2026-10-16 仙フィル394th   false',
    '2026-10-16 午後休講   false',
    '2026-10-16 大学祭リハーサル 17:00 19:30 true',
    '2026-10-17 大学祭演奏   true',
    '2026-10-18 大学祭   false',
    '2026-10-20 個人／パート 18:00 21:00 true',
    '2026-10-24 総合型選抜   false',
    '2026-10-25 総合型選抜   false',
    '2026-10-27 個人／パート 18:00 21:00 true',
    '2026-10-30 個人／パート 18:00 21:00 true',
  ]);
  assert.ok(items.every((i) => !i.error));
});

test('1行1件の書き方を読む', () => {
  const items = parse([
    '10/16(金) 大学祭リハーサル 17:00〜19:30',
    '10月20日 個人／パート １８：００～２１：００',
    '11/3 合奏 13:00-17:00、個人／パート 17:00〜18:00',
    '2027/1/9 合奏 9:30〜12:00',
    '12/24 本番',
  ].join('\n'));
  assert.deepEqual(brief(items), [
    '2026-10-16 大学祭リハーサル 17:00 19:30 true',
    '2026-10-20 個人／パート 18:00 21:00 true',
    '2026-11-03 合奏 13:00 17:00 true',
    '2026-11-03 個人／パート 17:00 18:00 true',
    '2027-01-09 合奏 09:30 12:00 true',
    '2026-12-24 本番   true',
  ]);
});

test('ありえない日付や時刻は誤りの印を付ける', () => {
  const items = parse('2/30 合奏 18:00〜20:00\n11/1 合奏 21:00〜20:00\n11/2 合奏 25:00〜26:00');
  assert.deepEqual(items.map((i) => i.error), ['日付が正しくありません', '終了が開始より前です', '時刻が正しくありません']);
});

test('年をまたぐ表は翌年として読む', () => {
  const items = parse(['2026年12月', ['12月27日', '28日', '29日', '30日', '31日', '1月1日', '2日'].join(T), ['', '', '', '', '', '', '合奏'].join(T)].join('\n'));
  assert.equal(items[0].date, '2027-01-02');
});
